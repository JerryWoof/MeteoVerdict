export const LANGUAGES = Object.keys(STRINGS);

/** The stored choice if valid, else Czech: the site is Czech first, English is the toggle. */
export function pickLanguage(stored) {
  return LANGUAGES.includes(stored) ? stored : "cs";
}

/** t(key, {name: value}) in one language, falling back to English, then to the key. */
export function translator(language) {
  const strings = STRINGS[language] ?? STRINGS.en;
  const date = dateFormat(language);
  return (key, params = {}) =>
    (strings[key] ?? STRINGS.en[key] ?? key).replace(/\{(\w+)\}/g, (_, name) => {
      const value = params[name] ?? "";
      const day = ISO_DAY.exec(value);
      return day ? `${date.format(new Date(`${day[1]}T12:00:00Z`))}${day[2] ?? ""}` : String(value);
    });
}

// a day "2026-10-19" (or a run "2026-10-19 00 UTC") in a text is shown in the language:
// "19. 10. 2026", "19 Oct 2026"
const ISO_DAY = /^(\d{4}-\d{2}-\d{2})( \d{2} UTC)?$/;
function dateFormat(language) {
  return language === "cs"
    ? new Intl.DateTimeFormat("cs", { day: "numeric", month: "numeric", year: "numeric", timeZone: "UTC" })
    : new Intl.DateTimeFormat("en-GB", { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" });
}

const STORAGE_KEY = "meteoverdict.language";

// the choice is a per-browser convenience; storage may be unavailable
export function storedLanguage() {
  try {
    return window.localStorage.getItem(STORAGE_KEY);
  } catch {
    return null;
  }
}

function storeLanguage(language) {
  try {
    window.localStorage.setItem(STORAGE_KEY, language);
  } catch {
    // keep working without storage
  }
}

/** Language of this page view; sets <html lang>, the [data-i18n] texts, the footer and the
 * switch. */
export function setUpLanguage() {
  const language = pickLanguage(storedLanguage());
  const t = translator(language);
  document.documentElement.lang = language;
  for (const element of document.querySelectorAll("[data-i18n]")) {
    element.textContent = t(element.dataset.i18n);
  }
  for (const element of document.querySelectorAll("[data-i18n-aria]")) {
    element.setAttribute("aria-label", t(element.dataset.i18nAria));
  }
  for (const element of document.querySelectorAll("[data-i18n-placeholder]")) {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  }
  for (const element of document.querySelectorAll("[data-i18n-alt]")) {
    element.alt = t(element.dataset.i18nAlt);
  }
  for (const element of document.querySelectorAll("[data-i18n-title]")) {
    element.title = t(element.dataset.i18nTitle);
    element.setAttribute("aria-label", element.title);
  }
  // the tab title in the page language (<title data-i18n-page="key">)
  const title = document.querySelector("title[data-i18n-page]");
  if (title) document.title = `MeteoVerdict: ${t(title.dataset.i18nPage)}`;
  for (const footer of document.querySelectorAll("footer[data-footer]")) {
    renderFooter(footer, t);
  }
  const toggle = document.getElementById("language");
  if (toggle) {
    toggle.textContent = t("language.switch");
    toggle.addEventListener("click", () => {
      storeLanguage(language === "cs" ? "en" : "cs");
      window.location.reload();
    });
  }
  return t;
}
